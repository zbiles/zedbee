import { createHash } from "node:crypto";
import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  copyFileSync,
  lstatSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
export const hookAssetFiles = Object.freeze([
  "index.cjs",
  "development.cjs",
  "production.cjs",
  "LICENSE",
  "provenance.json",
]);
const hash = (value) => createHash("sha256").update(value).digest("hex");
export function replaceAnalysis(
  input,
  analysis,
  expectedInput,
  expectedRegion,
) {
  if (hash(input) !== expectedInput)
    throw new Error("Hooks upstream input hash mismatch");
  const startMarker = "function validateNoSetStateInEffects(";
  const endMarker = "function validateNoJSXInTryStatement(";
  const start = input.indexOf(startMarker),
    end = input.indexOf(endMarker);
  if (
    start < 0 ||
    end <= start ||
    input.indexOf(startMarker, start + 1) !== -1 ||
    input.indexOf(endMarker, end + 1) !== -1
  )
    throw new Error("Hooks analysis boundaries mismatch");
  if (hash(input.slice(start, end)) !== expectedRegion)
    throw new Error("Hooks analysis region hash mismatch");
  return input.slice(0, start) + analysis + input.slice(end);
}
function readRegular(path) {
  if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink())
    throw new Error("Hooks asset must be a regular file");
  return readFileSync(path);
}
export function generateManagedHooks(root, write = false) {
  const pinRoot = join(root, "patches/react-hooks/7.1.1");
  const pin = JSON.parse(readRegular(join(pinRoot, "inputs.json")));
  const upstream = join(root, "node_modules/eslint-plugin-react-hooks");
  const installed = JSON.parse(readRegular(join(upstream, "package.json")));
  const manifest = JSON.parse(readRegular(join(root, "package.json")));
  const lock = JSON.parse(readRegular(join(root, "package-lock.json")));
  if (
    installed.version !== pin.version ||
    manifest.dependencies["eslint-plugin-react-hooks"] !== pin.version ||
    lock.packages["node_modules/eslint-plugin-react-hooks"].integrity !==
      pin.integrity
  )
    throw new Error("Hooks upstream version/integrity mismatch");
  const analysis = readRegular(join(pinRoot, "analysis.js")).toString("utf8");
  const outputs = {};
  for (const mode of ["development", "production"]) {
    const input = readRegular(
      join(upstream, `cjs/eslint-plugin-react-hooks.${mode}.js`),
    ).toString("utf8");
    outputs[`${mode}.cjs`] = Buffer.from(
      replaceAnalysis(
        input,
        analysis,
        pin.inputs[mode].sha256,
        pin.inputs[mode].regionSha256,
      ),
    );
  }
  outputs["index.cjs"] = Buffer.from(
    "'use strict';\nmodule.exports = require(process.env.NODE_ENV === 'production' ? './production.cjs' : './development.cjs');\n",
  );
  const license = readRegular(join(upstream, "LICENSE"));
  if (hash(license) !== pin.licenseSha256)
    throw new Error("Hooks license mismatch");
  outputs.LICENSE = license;
  const provenance = {
    ...pin,
    analysisSha256: hash(analysis),
    files: Object.fromEntries(
      Object.entries(outputs).map(([name, bytes]) => [name, hash(bytes)]),
    ),
  };
  outputs["provenance.json"] = Buffer.from(
    JSON.stringify(provenance, null, 2) + "\n",
  );
  const identity = `// Generated by npm run hooks:generate.\nexport const managedHooksRevision = ${JSON.stringify(pin.revision)};\nexport const managedHooksProvenanceSha256 = ${JSON.stringify(hash(outputs["provenance.json"]))};\n`;
  const assetRoot = join(root, "assets/react-hooks/7.1.1");
  if (write) mkdirSync(assetRoot, { recursive: true });
  for (const [name, bytes] of Object.entries(outputs)) {
    const target = join(assetRoot, name);
    if (write) writeFileSync(target, bytes);
    else if (!readRegular(target).equals(bytes))
      throw new Error(`Stale managed Hooks asset: ${name}`);
  }
  const identityPath = join(root, "src/checks/react/managed-hooks-identity.ts");
  if (write) writeFileSync(identityPath, identity);
  else if (readRegular(identityPath).toString("utf8") !== identity)
    throw new Error("Stale managed Hooks identity");
  return provenance;
}
export function copyManagedHooks(root) {
  generateManagedHooks(root, false);
  const target = join(root, "dist/vendor/react-hooks/7.1.1");
  mkdirSync(target, { recursive: true });
  for (const file of hookAssetFiles)
    copyFileSync(
      join(root, "assets/react-hooks/7.1.1", file),
      join(target, file),
    );
}
if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  if (
    !["--write", "--check"].includes(process.argv[2]) ||
    process.argv.length !== 3
  )
    throw new Error("Usage: generate-managed-react-hooks.mjs --write|--check");
  generateManagedHooks(process.cwd(), process.argv[2] === "--write");
  process.stdout.write("Managed Hooks artifacts verified.\n");
}
